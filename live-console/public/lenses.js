/* The five investors, and where each one's method breaks — in the browser.

   A port of advisor/masters.py and advisor/failures.py. Both have lived as
   command-line tools only, which meant the most distinctive thing this system
   does was invisible on the page people actually use.

   A port is where two implementations drift apart, so this one is pinned:
   tests-lenses.mjs runs three companies through it and asserts every score,
   every criterion and every failure verdict matches a fixture generated by the
   Python original.

   The thresholds here are the fixed fallbacks. The Python side can calibrate
   them against a live cross-section; the browser has no universe to compare
   against, so it uses the published levels and says so. */
(function () {
  "use strict";

  /* ---------- helpers: every one returns null rather than guessing ---------- */
  function pctOf(x) { return x == null ? "not disclosed" : (x * 100).toFixed(1) + "%"; }
  function numOf(x, d) {
    return x == null ? "not disclosed" : Number(x).toFixed(d == null ? 2 : d);
  }
  function ge(v, t) { return v == null ? null : v >= t; }
  function le(v, t) { return v == null ? null : v <= t; }
  function between(v, lo, hi) { return v == null ? null : (v >= lo && v <= hi); }

  function C(name, passed, seen, why, theme) {
    return { name: name, passed: passed, seen: seen, why: why, theme: theme || "other" };
  }

  function scoreOf(criteria) {
    var judged = criteria.filter(function (c) { return c.passed !== null; });
    var unknown = criteria.length - judged.length;
    if (!judged.length) return { score: null, judged: 0, unknown: unknown };
    var hit = judged.filter(function (c) { return c.passed; }).length;
    return { score: hit / judged.length, judged: judged.length, unknown: unknown };
  }

  function verdictOf(score, judged, unknown, total) {
    if (score === null) return "cannot judge — none of the criteria had data behind them";
    if (unknown > total / 2) {
      return "too thin to rely on — only " + judged + " of " + total +
             " criteria could be judged, so this is a hint, not a finding";
    }
    if (score >= 0.85) return "passes this lens cleanly";
    if (score >= 0.6) return "mostly passes, with the failures below worth understanding";
    if (score >= 0.35) return "fails more than it passes on this lens";
    return "this lens rejects it";
  }

  /* Did the line grow in most years, rather than once spectacularly? The
     criterion nearly every screener skips, because it needs history. */
  function consistency(series, minYears) {
    minYears = minYears == null ? 4 : minYears;
    if (!series || series.length < minYears + 1) return null;
    var ups = 0;
    for (var i = 1; i < series.length; i++) {
      if (series[i - 1] && series[i] && series[i] > series[i - 1]) ups++;
    }
    return ups >= (series.length - 1) * 0.7;
  }

  function lens(name, author, idea, criteria) {
    var s = scoreOf(criteria);
    return { lens: name, author: author, idea: idea, score: s.score,
             judged: s.judged, unknown: s.unknown, criteria: criteria,
             verdict: verdictOf(s.score, s.judged, s.unknown, criteria.length) };
  }

  /* ---------- PEG, derived here so it matches the growth shown beside it ---- */
  function derive(f) {
    var out = {};
    for (var k in f) out[k] = f[k];
    var g = out.earningsCagr3y || out.earningsGrowth;
    var pe = out.pe;
    if (out.peg == null) {
      out.peg = (pe && pe > 0 && g && g > 0.01) ? pe / (g * 100) : null;
    }
    return out;
  }

  /* ---------- the lenses ---------- */
  function qglp(f) {
    var hist = f.revenue_history;
    var g = f.earningsCagr3y || f.earningsGrowth;
    var rg = f.revenueCagr3y || f.revenueGrowth;
    return lens("QGLP", "Raamdeo Agrawal",
      "Quality, Growth, Longevity, Price — in that order, price last.", [
      C("Quality of business — returns on capital", ge(f.roce, 0.15), pctOf(f.roce),
        "A business earning less on capital than it costs is shrinking in real " +
        "terms however fast revenue grows.", "returns"),
      C("Quality of balance sheet — low debt", le(f.debtToEquity, 0.5),
        numOf(f.debtToEquity),
        "Leverage is what turns a bad few quarters into a permanent loss.", "debt"),
      C("Quality of earnings — profit converts to cash", ge(f.cashConversion, 0.75),
        numOf(f.cashConversion),
        "Profit that never becomes cash is the most common prelude to a restatement.",
        "cash"),
      C("Growth — earnings compounding", ge(g, 0.15), pctOf(g),
        "Over a decade the share price follows earnings and almost nothing else.",
        "growth"),
      C("Growth is real — sales grow too", ge(rg, 0.10), pctOf(rg),
        "Profit growing without sales growing is cost-cutting, and cost cutting " +
        "has a floor.", "growth"),
      C("Longevity — growth in most years, not one", consistency(hist),
        hist == null ? "history not available" : hist.length + " years on record",
        "Sustained compounding is the whole thesis; one good year is noise.",
        "consistency"),
      C("Longevity — reinvests at high returns", ge(f.roe, 0.15), pctOf(f.roe),
        "A compounder must be able to put retained profit back to work at the " +
        "same rate it earned it.", "returns"),
      C("Price — not paying for a decade in advance", le(f.peg, 1.5), numOf(f.peg),
        "Agrawal puts price last, not nowhere: a great business bought at any " +
        "price is still a bad investment.", "price"),
    ]);
  }

  var DURABLE = /consum|fmcg|pharma|health|bank|financ|insur|auto|retail|jewel|paint|food|beverage/;

  function jhunjhunwala(f) {
    var g = f.earningsCagr3y || f.earningsGrowth;
    var sector = (f.sector || "").toLowerCase();
    return lens("Buy early, sit tight", "Rakesh Jhunjhunwala",
      "Compounding earnings in businesses people will still need in a decade — " +
      "bought before consensus, held through noise, and never against the tape.", [
      C("Earnings compounding hard", ge(g, 0.20), pctOf(g),
        "He bought growth early and held it; 20% compounding doubles money in " +
        "under four years.", "growth"),
      C("High return on equity", ge(f.roe, 0.18), pctOf(f.roe),
        "The engine of compounding — a low-ROE business cannot compound however " +
        "cheap it looks.", "returns"),
      C("Debt under control", le(f.debtToEquity, 0.6), numOf(f.debtToEquity),
        "He concentrated heavily, and concentration plus leverage is how " +
        "investors are permanently removed from the game.", "debt"),
      C("Durable demand — needed in ten years",
        f.sector ? DURABLE.test(sector) : null, f.sector || "sector not identified",
        "His stated test: if people need it today they will need it in ten years. " +
        "Jewellery, medicines, cars, insurance.", "demand"),
      C("Not already priced for perfection", le(f.pe, 40), numOf(f.pe, 1),
        "He bought before the story was consensus, not after.", "price"),
      C("The tape agrees — above its long-term average",
        f.above200dma === undefined ? null : f.above200dma,
        f.above200dma == null ? "not computed" : (f.above200dma ? "above" : "below"),
        "\"Markets are supreme.\" He respected the trend and did not argue with a " +
        "falling price.", "tape"),
    ]);
  }

  function buffett(f) {
    return lens("Owner earnings", "Warren Buffett",
      "A business you would be happy to own outright, bought at a price that " +
      "leaves room for being wrong.", [
      C("Consistently high return on equity", ge(f.roe, 0.15), pctOf(f.roe),
        "The single number that best separates a franchise from a commodity.",
        "returns"),
      C("Little debt", le(f.debtToEquity, 0.5), numOf(f.debtToEquity),
        "A good business with too much debt is a bad investment.", "debt"),
      C("Wide, durable margins", ge(f.netMargin, 0.10), pctOf(f.netMargin),
        "Margin is pricing power made visible.", "margin"),
      C("Interest comfortably covered", ge(f.interestCover, 5),
        numOf(f.interestCover, 1),
        "Solvency is not a valuation question; it is a survival one.", "solvency"),
      C("Profit turns into cash", ge(f.cashConversion, 0.80), numOf(f.cashConversion),
        "Owner earnings, not reported earnings, are what an owner gets.", "cash"),
      C("Priced sensibly", le(f.pe, 25), numOf(f.pe, 1),
        "Price is what you pay; value is what you get.", "price"),
    ]);
  }

  function lynch(f) {
    var g = f.earningsCagr3y || f.earningsGrowth;
    return lens("Growth at a reasonable price", "Peter Lynch",
      "Buy growth, but never at a price that assumes it continues forever.", [
      C("Growth you are not overpaying for", le(f.peg, 1.0), numOf(f.peg),
        "The PEG ratio — his one genuinely original contribution.", "price"),
      C("Growing fast, but not implausibly", between(g, 0.15, 0.50), pctOf(g),
        "Above roughly 50% growth invites competition and cannot last.", "growth"),
      C("Balance sheet not stretched", le(f.debtToEquity, 0.5), numOf(f.debtToEquity),
        "Debt is what stops a good story surviving a bad year.", "debt"),
      C("Can pay its near-term bills", ge(f.currentRatio, 1.5), numOf(f.currentRatio),
        "Working capital is where growth companies die.", "solvency"),
    ]);
  }

  function damani(f) {
    var hist = f.revenue_history;
    return lens("Dull and durable", "Radhakishan Damani",
      "Boring, cash-generative, almost unleveraged businesses held for decades " +
      "rather than quarters.", [
      C("Almost no debt", le(f.debtToEquity, 0.3), numOf(f.debtToEquity),
        "Survives every cycle without needing anyone's permission.", "debt"),
      C("High return on capital employed", ge(f.roce, 0.18), pctOf(f.roce),
        "Efficiency of the whole business, not just the equity slice.", "returns"),
      C("Grows every year, dully", consistency(hist, 5),
        hist == null ? "history not available" : hist.length + " years",
        "He held for decades; the question is not how fast but how reliably.",
        "consistency"),
      C("Returns capital to owners", ge(f.dividendYield, 0.005), pctOf(f.dividendYield),
        "A business that cannot pay anything out for years is reinvesting or lying.",
        "payout"),
      C("Not a wild ride", le(f.annualVol, 0.40), pctOf(f.annualVol),
        "Volatility you can sit through is what makes a decades-long hold " +
        "possible at all.", "volatility"),
    ]);
  }

  var LENSES = [qglp, jhunjhunwala, buffett, lynch, damani];

  function applyAll(facts) {
    var f = derive(facts);
    return LENSES.map(function (fn) { return fn(f); });
  }

  /* ---------- consensus: keep the disagreement ---------- */
  function consensus(verdicts) {
    var usable = verdicts.filter(function (v) { return v.score !== null; });
    if (!usable.length) {
      return { ok: false, why: "no lens had enough data to judge this company" };
    }
    var passes = usable.filter(function (v) { return v.score >= 0.6; });
    var fails = usable.filter(function (v) { return v.score < 0.35; });

    // Group by theme, not by name: every lens words "debt" differently.
    var byTheme = {};
    usable.forEach(function (v) {
      v.criteria.forEach(function (c) {
        if (c.passed !== null && c.theme !== "other") {
          (byTheme[c.theme] = byTheme[c.theme] || []).push(c.passed);
        }
      });
    });
    var uFail = Object.keys(byTheme).filter(function (t) {
      return byTheme[t].length >= 2 && !byTheme[t].some(Boolean); }).sort();
    var uPass = Object.keys(byTheme).filter(function (t) {
      return byTheme[t].length >= 2 && byTheme[t].every(Boolean); }).sort();

    var stance;
    if (passes.length >= 4) stance = "rare agreement — four or more independent methods accept it";
    else if (passes.length >= 2 && !fails.length) stance = "broad acceptance, no lens actively rejects it";
    else if (passes.length && fails.length) stance = "genuinely contested — read the split below before deciding";
    else if (!passes.length && fails.length) stance = "rejected across the board";
    else stance = "nothing here is compelling in either direction";

    return {
      ok: true, lenses_judging: usable.length,
      accepted_by: passes.map(function (v) { return v.author; }),
      rejected_by: fails.map(function (v) { return v.author; }),
      stance: stance,
      unanimous_strengths: uPass, unanimous_weaknesses: uFail,
    };
  }

  /* ---------- where each method breaks ---------- */
  var QUALITY_LENSES = ["Raamdeo Agrawal", "Warren Buffett", "Radhakishan Damani"];
  var VALUE_LENSES = ["Warren Buffett", "Peter Lynch"];
  var TREND_LENSES = ["Rakesh Jhunjhunwala"];
  var ALL_LENSES = ["Raamdeo Agrawal", "Rakesh Jhunjhunwala", "Warren Buffett",
                    "Peter Lynch", "Radhakishan Damani"];
  var CYCLICAL = /metal|mining|steel|cement|commodity|chemical|oil|gas|energy|shipping|sugar|paper|auto/;

  function F(name, trig, serious, invalidates, evidence, mechanism, todo) {
    return { name: name, triggered: trig,
             severity: trig === null ? "unknown" : (!trig ? "none" : (serious ? "serious" : "watch")),
             invalidates: invalidates, evidence: evidence,
             mechanism: mechanism, what_to_do: todo };
  }

  function qualityTrap(f) {
    if (f.roe == null || f.pe_percentile == null ||
        f.earningsGrowth == null || f.earningsCagr3y == null) {
      return F("Quality trap", null, false, QUALITY_LENSES,
        "needs return on equity, valuation percentile and both growth rates",
        "A quality lens cannot see its own blind spot; this check needs the " +
        "company's valuation history, which the lens never looks at.",
        "Get the valuation history before trusting a quality endorsement.");
    }
    var trig = f.roe >= 0.18 && f.pe_percentile >= 0.80 &&
               f.earningsGrowth < f.earningsCagr3y - 0.03;
    return F("Quality trap", trig, f.pe_percentile >= 0.90, QUALITY_LENSES,
      "return on equity " + (f.roe * 100).toFixed(0) + "%, valuation at the " +
      (f.pe_percentile * 100).toFixed(0) + "th percentile of its own history, growth " +
      (f.earningsGrowth * 100).toFixed(0) + "% against a three-year rate of " +
      (f.earningsCagr3y * 100).toFixed(0) + "%",
      "Returns on capital and margins describe the franchise that was built; they " +
      "say nothing about what is being paid for it now. When growth decelerates " +
      "from a rich starting valuation, the derating alone can take years of " +
      "earnings growth back.",
      "Do not treat the quality lenses as confirming anything here. Require a " +
      "valuation case on its own terms, or wait for the derating.");
  }

  function valueTrap(f) {
    if (f.pe == null || f.roe == null || f.roe_3y_ago == null || f.above200dma == null) {
      return F("Value trap", null, false, VALUE_LENSES,
        "needs valuation, returns now against three years ago, and the trend",
        "Cheapness is only information alongside the direction of the business " +
        "and the direction of the price.",
        "Get the earlier return on equity before acting on a low multiple.");
    }
    var trig = f.pe > 0 && f.pe <= 15 && f.roe < f.roe_3y_ago - 0.03 &&
               f.above200dma === false;
    return F("Value trap", trig, f.roe < f.roe_3y_ago - 0.08, VALUE_LENSES,
      "price-earnings " + f.pe.toFixed(1) + ", return on equity " +
      (f.roe * 100).toFixed(0) + "% against " + (f.roe_3y_ago * 100).toFixed(0) +
      "% three years ago, price " + (f.above200dma ? "above" : "below") +
      " its long-term average",
      "A falling multiple on falling returns is not mean reversion. The multiple " +
      "is low because earnings are expected to be lower still, and the accounts " +
      "are the last place that shows up.",
      "Require evidence the deterioration has stopped before treating cheapness " +
      "as a reason.");
  }

  function cyclicalPeg(f) {
    if (!f.sector || f.peg == null || f.opMargin == null || f.opMargin_5y_high == null) {
      return F("Cyclical PEG illusion", null, false, ["Peter Lynch"],
        "needs the sector, PEG, and margin against its five-year high",
        "PEG assumes earnings are a trend. In a cyclical they are a wave.",
        "Get the margin history before using PEG on a cyclical.");
    }
    var cyc = CYCLICAL.test((f.sector || "").toLowerCase());
    var atPeak = f.opMargin_5y_high > 0 && f.opMargin >= f.opMargin_5y_high * 0.92;
    var trig = cyc && atPeak && f.peg <= 1.0;
    return F("Cyclical PEG illusion", trig, atPeak && f.peg <= 0.6, ["Peter Lynch"],
      f.sector + ", PEG " + f.peg.toFixed(2) + ", operating margin " +
      (f.opMargin * 100).toFixed(1) + "% against a five-year high of " +
      (f.opMargin_5y_high * 100).toFixed(1) + "%",
      "Peak-cycle earnings make every valuation ratio look cheap at once. The " +
      "correct multiple for a cyclical at the top of its margin range is a high " +
      "one, not a low one.",
      "Value it on mid-cycle margins, not current ones.");
  }

  function momentumReversal(f) {
    if (f.market_drawdown == null || f.market_rebounding == null) {
      return F("Momentum reversal", null, false, TREND_LENSES,
        "needs the index drawdown and whether it has turned up",
        "A trend rule cannot tell a continuation from a turn; only the market's " +
        "own state hints at which is likelier.",
        "Track the index drawdown to know when trend signals are fragile.");
    }
    var trig = f.market_drawdown <= -0.20 && f.market_rebounding === true;
    return F("Momentum reversal", trig, f.market_drawdown <= -0.30, TREND_LENSES,
      "index " + (f.market_drawdown * 100).toFixed(0) + "% from its high and " +
      (f.market_rebounding ? "turning up" : "still falling"),
      "Momentum crashes happen in rebounds, not in falls. The names that fell " +
      "hardest rise fastest, and a trend filter is by construction out of all of them.",
      "Suspend the tape requirement during the rebound, or size trend-based " +
      "entries down until the index reclaims its long-term average.");
  }

  function crowding(f) {
    if (f.institutionalHolding == null || f.pe_percentile == null) {
      return F("Crowded position", null, false, ALL_LENSES,
        "needs institutional ownership and the valuation percentile",
        "Checklists measure the business, never who already owns it.",
        "Get the shareholding pattern before adding to a consensus name.");
    }
    var trig = f.institutionalHolding >= 0.55 && f.pe_percentile >= 0.75;
    return F("Crowded position", trig, f.institutionalHolding >= 0.70, ALL_LENSES,
      "institutions hold " + (f.institutionalHolding * 100).toFixed(0) +
      "%, valuation at the " + (f.pe_percentile * 100).toFixed(0) +
      "th percentile of its own history",
      "When the informed buyers have finished buying, the next large flow is more " +
      "likely to be a seller. Ownership is a better guide to who is left to act " +
      "than any fundamental ratio.",
      "Size smaller than the checklists suggest, and prefer names where the same " +
      "quality has not yet been fully recognised.");
  }

  function accountingDivergence(f) {
    if (f.cashConversion == null || f.cashConversion_3y_avg == null ||
        f.earningsGrowth == null) {
      return F("Earnings not becoming cash", null, false, ALL_LENSES,
        "needs cash conversion now and its three-year average",
        "Every lens here is built on reported profit. None of them checks whether " +
        "the profit arrived.",
        "Get the cash flow statement; this is the check worth having most.");
    }
    var trig = f.earningsGrowth > 0.05 && f.cashConversion < 0.6 &&
               f.cashConversion < f.cashConversion_3y_avg - 0.20;
    return F("Earnings not becoming cash", trig, f.cashConversion < 0.4, ALL_LENSES,
      "cash conversion " + f.cashConversion.toFixed(2) + " against a three-year " +
      "average of " + f.cashConversion_3y_avg.toFixed(2) + ", while earnings grow " +
      (f.earningsGrowth * 100).toFixed(0) + "%",
      "Profit that does not convert to cash is either being consumed by working " +
      "capital or was never really earned. Both end the same way, and no ratio " +
      "built on reported earnings sees either coming.",
      "Treat every lens's endorsement as suspended until cash conversion recovers. " +
      "This overrides quality, value and trend alike.");
  }

  var CHECKS = [qualityTrap, valueTrap, cyclicalPeg, momentumReversal,
                crowding, accountingDivergence];

  function runAll(facts) {
    var f = derive(facts);
    return CHECKS.map(function (fn) { return fn(f); });
  }

  /* Which endorsements to stop trusting, and why. */
  function discount(facts, verdicts) {
    var modes = runAll(facts);
    var fired = modes.filter(function (m) { return m.triggered === true; });
    var untestable = modes.filter(function (m) { return m.triggered === null; });

    var suspended = {};
    fired.forEach(function (m) {
      m.invalidates.forEach(function (a) {
        (suspended[a] = suspended[a] || []).push(m.name);
      });
    });
    var standing = verdicts.filter(function (v) {
      return v.score !== null && v.score >= 0.6 && !suspended[v.author];
    }).map(function (v) { return v.author; });

    var headline;
    if (!fired.length) {
      headline = untestable.length
        ? "no failure mode fired, but " + untestable.length +
          " could not be tested for want of data"
        : "no known failure mode is active — the lenses can be read at face value";
    } else if (fired.some(function (m) { return m.severity === "serious"; })) {
      headline = fired.length + " failure mode(s) active, at least one serious — " +
                 "the endorsements below are not reliable right now";
    } else {
      headline = fired.length + " failure mode(s) worth watching before acting";
    }

    return { headline: headline, fired: fired,
             untestable: untestable.map(function (m) { return m.name; }),
             suspended_authors: suspended,
             endorsements_still_standing: standing,
             all_modes: modes };
  }

  window.ADV_LENSES = {
    applyAll: applyAll, consensus: consensus, runAll: runAll,
    discount: discount, derive: derive,
    lenses: { qglp: qglp, jhunjhunwala: jhunjhunwala, buffett: buffett,
              lynch: lynch, damani: damani },
  };
})();
